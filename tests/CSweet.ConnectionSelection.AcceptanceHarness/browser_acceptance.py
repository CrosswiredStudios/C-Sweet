from pathlib import Path
from playwright.sync_api import sync_playwright, expect
out = Path('artifacts/selection-browser'); out.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    page=browser.new_page()
    page.goto('http://127.0.0.1:5391'); page.get_by_test_id('interactive-ready').wait_for(state='attached')
    expect(page.get_by_role('button',name='Save choice',exact=True)).to_be_visible()
    page.get_by_role('button',name='Continue',exact=True).click()
    expect(page.get_by_test_id('continued')).to_have_text('1')
    page.get_by_role('button',name='Back',exact=True).click()
    page.get_by_role('button',name='Return to connections',exact=True).click()
    expect(page.get_by_text('Skip for now',exact=True)).to_be_visible()
    page.locator('.mud-select').first.click()
    page.get_by_text('Self-hosted service',exact=True).click()
    page.get_by_label('Your service HTTPS address').fill('https://selfhost.example.test')
    page.get_by_role('button',name='Save choice',exact=True).click()
    page.reload(); page.get_by_test_id('interactive-ready').wait_for(state='attached')
    expect(page.get_by_label('Your service HTTPS address')).to_have_value('https://selfhost.example.test')
    page.get_by_role('button',name='Check service',exact=True).click()
    expect(page.get_by_text('Service status: currently unavailable or unsupported.',exact=False)).to_be_visible()
    page.screenshot(path=str(out/'selfhost-unavailable.png'), full_page=True)
    page.goto('http://127.0.0.1:5391/settings'); page.get_by_test_id('interactive-ready').wait_for(state='attached')
    expect(page.get_by_label('Your service HTTPS address')).to_have_value('https://selfhost.example.test')
    page.locator('.mud-select').first.click(); page.get_by_text('Skip for now',exact=True).click()
    page.get_by_role('button',name='Save choice',exact=True).click()
    page.reload(); page.get_by_test_id('interactive-ready').wait_for(state='attached'); expect(page.get_by_text('Skip for now',exact=True)).to_be_visible()
    expect(page.get_by_role('button',name='Check service',exact=True)).to_be_disabled()
    page.get_by_role('button',name='Continue',exact=True).click(); expect(page.get_by_test_id('continued')).to_have_text('1')
    page.screenshot(path=str(out/'settings-skipped.png'), full_page=True)
    browser.close()
print('PASS: actual shared Razor component skip, back, repeat, saved reload/interruption, Settings reuse and unavailable-service continuation. Synthetic HTTP adapter; product auth tested separately.')
