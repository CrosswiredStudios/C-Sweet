"""Generate the appearance stylesheet and ID list from the committed theme catalog.
Source of truth: src/CSweet.UI/Services/AppearanceThemes.json.
Validates text contrast on every surface. Run with --check to detect drift.
"""
from pathlib import Path
import argparse, json, math
ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "src/CSweet.UI/Services/AppearanceThemes.json"
GENERATOR = "scripts/Sync-AppearanceThemes.py"
def rgb(h): return [int(h[i:i+2], 16) for i in (1,3,5)]
def byte(n): return f"{math.floor(n + .5):02x}"
def alpha(h, a): return h[:7] + byte(a * 255) if a < 1 else h[:7]
def mix(a,b,t): return "#" + "".join(byte(x+(y-x)*t) for x,y in zip(rgb(a),rgb(b)))
def luminance(h):
    def ch(v):
        s = v/255
        return s/12.92 if s <= .03928 else ((s+.055)/1.055)**2.4
    return sum(w*ch(v) for w,v in zip((.2126,.7152,.0722),rgb(h)))
def contrast(a,b):
    la,lb=luminance(a),luminance(b)
    hi,lo=max(la,lb),min(la,lb)
    return (hi+.05)/(lo+.05)
def validate(themes):
    """Keep readable text on every surface where the token is used."""
    ids=[t["id"] for t in themes]
    assert len(ids)==len(set(ids)), "Duplicate theme IDs"
    assert ids[0]=="night-glass", "Night Glass must remain the default (first) theme"
    for theme in themes:
        t=theme["tokens"]
        # warm/mint, danger, ok and accent-2 also colour text (links, errors, status); accent-3 only marks UI.
        for token,target in (("ink",4.5),("muted",4.5),("faint",3.0),("warm",4.5),("danger",4.5),("ok",4.5),("accent-2",4.5),("accent-3",3.0)):
            for surface in ("paper","surface","elevated"):
                ratio=contrast(t[token],t[surface])
                assert ratio>=target, f"{theme['id']}: {token} on {surface} is {ratio:.2f}:1 (needs {target}:1)"
        theme["isDark"]=luminance(t["paper"]) <= .4
def outputs(themes):
    css=[f"/* Generated by {GENERATOR}. Do not edit by hand. */"]
    for theme in themes:
        t=theme["tokens"]; selector=f':root[data-appearance="{theme["id"]}"]'
        if theme["id"]=="night-glass": selector=":root, " + selector
        css.append(selector+" {")
        css.append("    color-scheme: "+("dark" if theme["isDark"] else "light")+";")
        for key,value in t.items(): css.append(f"    --{key}: {value};")
        contrast_ink="#000000" if luminance(t["warm"]) > .179 else "#ffffff"
        derived={"sunken":t["paper"],"mint":t["warm"],"mint-soft":alpha(t["warm"],.14 if theme["isDark"] else .10),
            "mint-ink":contrast_ink,"action":t["warm"],"action-ink":contrast_ink,"warm-soft":alpha(t["warm"],.14),
            "ok-ink":"#000000" if luminance(t["ok"])>.179 else "#ffffff",
            "info-ink":"#000000" if luminance(t["accent-2"])>.179 else "#ffffff",
            "danger-darken":mix(t["danger"],"#000000",.2),
            "z-1":"inset 0 1px 0 var(--sheen)","z-2":"0 12px 32px -16px #00000066, inset 0 1px 0 var(--sheen)",
            "z-3":"0 24px 64px -16px #00000080, inset 0 1px 0 var(--sheen)"}
        for key,value in derived.items(): css.append(f"    --{key}: {value};")
        css.append("}")
    ids=[t["id"] for t in themes]
    paper={t["id"]:t["tokens"]["paper"] for t in themes}
    js=(f"// Generated by {GENERATOR}.\nwindow.csweetThemeIds = new Set("+json.dumps(ids)+");\n"
        "// Page colour per theme, for the browser theme-color before stylesheets load.\n"
        "window.csweetThemePaper = "+json.dumps(paper)+";\n")
    return {CATALOG:json.dumps(themes,indent=2)+"\n",
        ROOT/"src/CSweet.UI/wwwroot/css/presets.css":"\n".join(css)+"\n",
        ROOT/"src/CSweet.UI/wwwroot/js/themeCatalog.js":js}
if __name__=="__main__":
    parser=argparse.ArgumentParser(); parser.add_argument("--check",action="store_true"); args=parser.parse_args()
    themes=json.loads(CATALOG.read_text(encoding="utf-8"))
    validate(themes)
    for path,content in outputs(themes).items():
        if args.check: assert path.exists() and path.read_text(encoding="utf-8")==content, f"Out of sync: {path}"
        else: path.write_text(content,encoding="utf-8")
    print(f"{len(themes)} appearance themes: " + ("verified" if args.check else "synchronized"))
