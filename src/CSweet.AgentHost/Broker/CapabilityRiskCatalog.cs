    /// <summary>Every capability with an explicit risk class, for inspection and diagnostics.</summary>
    public static IReadOnlyDictionary<string, CapabilityRiskClass> All => Table;

    /// <summary>The risk class of a capability, falling back to <see cref="DefaultRisk"/> when unknown.</summary>
    public static CapabilityRiskClass Classify(string? capabilityName) =>
        capabilityName is not null && Table.TryGetValue(capabilityName, out var risk) ? risk : DefaultRisk;

    /// <summary>True when the capability appears in the explicit table.</summary>
    public static bool IsKnown(string? capabilityName) =>
        capabilityName is not null && Table.ContainsKey(capabilityName);
