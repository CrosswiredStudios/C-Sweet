/// and the audit trail all read from this one table instead of re-deriving "is this dangerous?" at
/// each call site.
/// </summary>
/// <remarks>
/// Names are the exact strings the handlers dispatch on (the <c>CanHandle</c> implementations in this
/// folder and the descriptors in <see cref="McpToolCatalog"/>); nothing here is inferred from a name.
/// Handlers receive the raw string, so the table is keyed ordinally. A capability the broker learns
